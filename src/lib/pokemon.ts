export function getPokemonSprite(name: string, points: number, customFamilyId?: number | null) {
  let familyIndex = 0;
  
  if (customFamilyId !== undefined && customFamilyId !== null && customFamilyId >= 0 && customFamilyId < pokemonFamilies.length) {
    familyIndex = customFamilyId;
  } else {
    // Deterministic hash
    let hash = 0;
    for (let i = 0; i < name.length; i++) {
      hash = name.charCodeAt(i) + ((hash << 5) - hash);
    }
    familyIndex = Math.abs(hash) % pokemonFamilies.length;
  }
  
  const family = pokemonFamilies[familyIndex].stages;
  
  let stage = 0;
  if (points >= 16 && points < 40) stage = 1;
  if (points >= 40) stage = 2;
  
  const pokemonId = family[stage];
  
  // Usando a base de dados oficial do Pokemon Showdown que inclui GIFs animados até da geração 9!
  return `https://raw.githubusercontent.com/PokeAPI/sprites/master/sprites/pokemon/other/showdown/${pokemonId}.gif`;
}
